// --- seeded RNG (mulberry32) + Box-Muller -----------------------------------
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function gauss(r) {
  const u = Math.max(r(), 1e-12);
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * r());
}
function hash(str) {
  let h = 2166136261;
  for (const c of str) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
}

function businessDays(from, to) {
  const out = [];
  const d = new Date(from + "T00:00:00Z");
  const end = new Date(to + "T00:00:00Z");
  while (d <= end) {
    const wd = d.getUTCDay();
    if (wd !== 0 && wd !== 6) out.push(d.toISOString().slice(0, 10));
    d.setUTCDate(d.getUTCDate() + 1);
  }
  return out;
}

function generate(ticker, { vol, a }) {
  const r = rng(hash(ticker));
  const anchors = [...a].sort((x, y) => x[0].localeCompare(y[0]));
  const prices = [];
  for (let k = 0; k < anchors.length - 1; k++) {
    const [d0, p0] = anchors[k];
    const [d1, p1] = anchors[k + 1];
    const days = businessDays(d0, d1);
    const n = days.length - 1;
    // Brownian bridge in log space from ln(p0) to ln(p1)
    const walk = [0];
    for (let i = 1; i <= n; i++) walk.push(walk[i - 1] + vol * gauss(r));
    const l0 = Math.log(p0);
    const l1 = Math.log(p1);
    const start = k === 0 ? 0 : 1; // avoid duplicating anchor days
    for (let i = start; i <= n; i++) {
      const t = n === 0 ? 1 : i / n;
      const bridge = walk[i] - t * walk[n];
      const lp = l0 + t * (l1 - l0) + bridge;
      prices.push([days[i], Math.round(Math.exp(lp) * 10000) / 10000]);
    }
  }
  return prices.filter(([d]) => d <= END);
}

mkdirSync(DATA_DIR, { recursive: true });
const generated = {};
for (const [ticker, spec] of Object.entries(S)) {
  let prices;
  if (spec.from) {
    prices = generated[spec.from].map(([d, p]) => [d, Math.round(p * spec.scale * 10000) / 10000]);
  } else {
    prices = generate(ticker, spec);
  }
  generated[ticker] = prices;
  const note =
    ticker === "VOO" ? "PLACEHOLDER. Real file splices SPY before VOO's 2010-09-09 launch." :
    ticker === "QQQM" ? "PLACEHOLDER. Real file splices QQQ before QQQM's 2020-10-13 launch." :
    "PLACEHOLDER synthetic data shaped like real history. Run scripts/fetch-data.py for real prices.";
  const payload = { ticker, source: "placeholder", adjusted: true, generated: "sample", note, prices };
  writeFileSync(join(DATA_DIR, `${ticker}.json`), JSON.stringify(payload));
  console.log(`${ticker.padEnd(5)} ${String(prices.length).padStart(5)} days  ${prices[0][0]} -> ${prices.at(-1)[0]}`);
}
